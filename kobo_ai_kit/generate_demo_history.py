#!/usr/bin/env python3
"""
Synthetic DEMO history for the four Forge sandbox traders, as a JSON file the team's seed script can load.

    python generate_demo_history.py                    # writes demo_history.json
    python generate_demo_history.py --end 2026-11-08 --out demo_history.json

Format (money is integer KOBO, times are UTC ISO, as in PRD v3):
  {"_demo_data": true, "_note": "...", "history_end": "2026-11-08",
   "traders": [{"key","fullName","accountNumber","archetype","preferredLanguage","firstDay"}],
   "inflows": [{"reference","accountNumber","amountKobo","at","channel"}]}
Every record is SYNTHETIC. Account numbers and names are the sandbox's own demo accounts (PRD section 7.2), never real ones.
Stories (change them in TRADERS below): Adaeze = steady (Smart Rate suggests a higher rate), Babatunde = steady and strong,
Musa = volatile (Smart Rate suggests easing), Efosa = brand new (only 9 days: no suggestion yet).
"""
import sys as _sys
from pathlib import Path as _Path

_HERE = str(_Path(__file__).resolve().parent)
if _HERE not in _sys.path:
    _sys.path.insert(0, _HERE)

import argparse
import json
from datetime import date

import numpy as np

import generate_seed as gs

TRADERS = [
    dict(key="adaeze", fullName="Adaeze Okonkwo", accountNumber="0123456789", archetype="steady", lang="igbo",
         mean=45000, cv=0.12, zero_p=0.04, ticket=2500, days=90),
    dict(key="babatunde", fullName="Babatunde Adeyemi", accountNumber="0123456790", archetype="steady_strong", lang="yoruba",
         mean=52000, cv=0.10, zero_p=0.03, ticket=6000, days=90),
    dict(key="musa", fullName="Musa Abdullahi", accountNumber="0123456791", archetype="volatile", lang="hausa",
         mean=30000, cv=0.80, zero_p=0.20, ticket=6000, days=90),
    dict(key="efosa", fullName="Efosa Osagie", accountNumber="0123456792", archetype="new_trader", lang="pidgin",
         mean=22000, cv=0.30, zero_p=0.05, ticket=3000, days=9),
]


def build(end: date, seed=42):
    gs.HISTORY_END = end
    gs.PROFILES = [dict(id=t["key"], profile=t["archetype"], full_name=t["fullName"], business=t["fullName"], lang=t["lang"],
                        mean=t["mean"], cv=t["cv"], zero_p=t["zero_p"], ticket=t["ticket"], days=t["days"], sick_last=0)
                   for t in TRADERS]
    merchants, inflows, _ = gs.build_history(np.random.default_rng(seed))
    acct = {t["key"]: t["accountNumber"] for t in TRADERS}
    first = {m["id"]: m["created_at"][:10] for m in merchants}
    out_in = [{"reference": "SEED-" + r["bank_reference"].split("-")[-1], "accountNumber": acct[r["merchant_id"]],
               "amountKobo": int(round(r["amount"] * 100)), "at": r["settled_at"], "channel": r["channel"]} for r in inflows]
    traders = [{"key": t["key"], "fullName": t["fullName"], "accountNumber": t["accountNumber"], "archetype": t["archetype"],
                "preferredLanguage": t["lang"], "firstDay": first[t["key"]]} for t in TRADERS]
    return {"_demo_data": True,
            "_note": "SYNTHETIC demo history for the Forge sandbox traders. Not real. Generated by generate_demo_history.py (seed 42).",
            "history_end": end.isoformat(), "traders": traders, "inflows": out_in}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--end", default="2026-11-08", help="last day of history (the day before the demo)")
    ap.add_argument("--out", default="demo_history.json")
    a = ap.parse_args(argv)
    doc = build(date.fromisoformat(a.end))
    Path = _Path
    Path(a.out).write_text(json.dumps(doc, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    per = {t["key"]: sum(1 for i in doc["inflows"] if i["accountNumber"] == t["accountNumber"]) for t in TRADERS}
    print(f"Wrote {a.out}: {len(doc['inflows'])} synthetic inflows for {len(doc['traders'])} traders {per}")
    return 0


if __name__ == "__main__":
    sys_exit = main()
    raise SystemExit(sys_exit)
